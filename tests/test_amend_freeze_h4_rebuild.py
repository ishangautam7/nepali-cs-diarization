"""Tests for scripts/amend_freeze_h4_rebuild.py (stdlib + pytest; no data, no numpy)."""
from __future__ import annotations

import hashlib
import importlib.util
import json
from pathlib import Path

import pytest

SPEC = importlib.util.spec_from_file_location(
    "amend_freeze_h4_rebuild", Path(__file__).resolve().parents[1] / "scripts/amend_freeze_h4_rebuild.py")
A = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(A)


def _h(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


@pytest.fixture
def world(tmp_path, monkeypatch):
    """A fake HOME with two pinned files, a fake repo with one guarded code file, and a FREEZE_H4.json."""
    home, repo = tmp_path / "home", tmp_path / "repo"
    (home / "data/d1").mkdir(parents=True)
    (home / "data/d1/same.csv").write_bytes(b"same content\n")
    (home / "data/d1/new.npz").write_bytes(b"regenerated bytes")
    (repo / "csdiar").mkdir(parents=True)
    (repo / "csdiar/code.py").write_text("x = 1\n")
    (repo / "planning").mkdir()
    rec = {"tag": "h4-freeze", "paths": {"out": "~/data/d1/results/h4"},
           "code_sha256": {"csdiar/code.py": _h(b"x = 1\n")},
           "feature_sha256": {"~/data/d1/same.csv": _h(b"same content\n"), "~/data/d1/new.npz": _h(b"old bytes")},
           "feature_bytes": {"~/data/d1/same.csv": 13, "~/data/d1/new.npz": 9}, "amendments": []}
    freeze = repo / "planning/FREEZE_H4.json"
    freeze.write_text(json.dumps(rec, indent=1) + "\n")
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setattr(A, "REPO", repo)
    return {"home": home, "repo": repo, "freeze": freeze, "report": tmp_path / "report.json",
            "out": home / "data/d1/results/h4"}


def _hash(w):
    return A.main(["hash", "--freeze", str(w["freeze"]), "--out", str(w["report"])])


def _amend(w, note="regenerated after the box loss"):
    return A.main(["amend", "--freeze", str(w["freeze"]), "--report", str(w["report"]), "--note", note])


def _verify(w):
    return A.main(["verify", "--freeze", str(w["freeze"])])


def _edit(path: Path, fn):
    d = json.loads(path.read_text())
    fn(d)
    path.write_text(json.dumps(d, indent=1) + "\n")


def test_hash_amend_verify_records_identical_and_changed(world):
    assert _hash(world) == 0
    rep = json.loads(world["report"].read_text())
    assert rep["what"] == A.REPORT_WHAT and rep["one_shot_files"] == []
    assert rep["files"]["~/data/d1/new.npz"] == {"sha256": _h(b"regenerated bytes"), "bytes": 17}
    assert _amend(world) == 0
    rec = json.loads(world["freeze"].read_text())
    am = rec["amendments"][-1]
    assert am["id"] == A.AMENDMENT_ID and am["deviation"] == 6
    assert am["identical"] == ["~/data/d1/same.csv"]
    assert am["changed"] == {"~/data/d1/new.npz": {"old_sha256": _h(b"old bytes"),
                                                    "new_sha256": _h(b"regenerated bytes"),
                                                    "old_bytes": 9, "new_bytes": 17}}
    assert rec["feature_sha256"]["~/data/d1/new.npz"] == _h(b"regenerated bytes")
    assert rec["feature_bytes"]["~/data/d1/new.npz"] == 17
    assert list(rec["feature_sha256"]) == ["~/data/d1/same.csv", "~/data/d1/new.npz"]   # key order kept
    assert rec["code_sha256"] == {"csdiar/code.py": _h(b"x = 1\n")}                      # nothing else changes
    assert "m3_artifacts_sha256" not in rec                     # left for freeze_h4 add-m3
    assert _verify(world) == 0


def test_hash_refuses_a_missing_pinned_file(world):
    (world["home"] / "data/d1/new.npz").unlink()
    with pytest.raises(SystemExit, match="missing"):
        _hash(world)


@pytest.mark.parametrize("name", list(A.ONE_SHOT))
def test_hash_refuses_once_either_stage_has_run_or_started(world, name):
    world["out"].mkdir(parents=True)
    (world["out"] / name).write_text("")
    with pytest.raises(SystemExit, match="already run or started"):
        _hash(world)


def test_a_dry_run_output_is_not_a_one_shot_file(world):
    world["out"].mkdir(parents=True)
    (world["out"] / "confirm_h4_stage1_dryrun.json").write_text("{}")
    assert _hash(world) == 0 and _amend(world) == 0 and _verify(world) == 0


def test_amend_refuses_a_report_listing_one_shot_files(world):
    _hash(world)
    _edit(world["report"], lambda r: r.update(one_shot_files=["confirm_h4_stage1.started"]))
    with pytest.raises(SystemExit, match="already run or started"):
        _amend(world)


def test_amend_refuses_a_report_that_does_not_cover_the_pinned_files(world):
    _hash(world)
    _edit(world["report"], lambda r: r["files"].pop("~/data/d1/same.csv"))
    with pytest.raises(SystemExit, match="cover exactly"):
        _amend(world)


@pytest.mark.parametrize("entry", [{}, {"sha256": "abc", "bytes": 3}, {"sha256": "0" * 64}])
def test_amend_refuses_a_malformed_report_entry(world, entry):
    _hash(world)
    _edit(world["report"], lambda r: r["files"].update({"~/data/d1/new.npz": entry}))
    with pytest.raises(SystemExit, match="lacks a SHA-256 or a size"):
        _amend(world)


def test_amend_refuses_something_that_is_not_a_hash_report(world):
    _hash(world)
    _edit(world["report"], lambda r: r.update(what="something else"))
    with pytest.raises(SystemExit, match="not a rebuild hash report"):
        _amend(world)


def test_amend_refuses_a_report_made_against_another_record(world):
    _hash(world)
    _edit(world["freeze"], lambda r: r.update(seed=1))
    with pytest.raises(SystemExit, match="different FREEZE_H4.json"):
        _amend(world)


def test_amend_refuses_when_feature_bytes_is_incomplete(world):
    _edit(world["freeze"], lambda r: r["feature_bytes"].pop("~/data/d1/new.npz"))
    _hash(world)
    with pytest.raises(SystemExit, match="feature_bytes"):
        _amend(world)


def test_amend_refuses_once_m3_artifacts_are_pinned(world):
    _edit(world["freeze"], lambda r: r.update(m3_artifacts_sha256={"~/data/m3/runs/x/best.pt": "0" * 64}))
    _hash(world)
    with pytest.raises(SystemExit, match="M3 artifacts are already pinned"):
        _amend(world)


def test_amend_refuses_changed_guarded_code(world):
    _hash(world)
    (world["repo"] / "csdiar/code.py").write_text("x = 2\n")
    with pytest.raises(SystemExit, match="changed since the freeze"):
        _amend(world)


def test_amend_refuses_twice_and_an_empty_note(world):
    _hash(world)
    with pytest.raises(SystemExit, match="--note"):
        _amend(world, note="  ")
    assert _amend(world) == 0
    _hash(world)                                      # a fresh report against the amended record
    with pytest.raises(SystemExit, match="already recorded"):
        _amend(world)


def test_verify_refuses_without_the_amendment(world):
    with pytest.raises(SystemExit, match="does not hold the rebuild amendment"):
        _verify(world)


def test_verify_catches_a_file_changed_after_hashing(world):
    _hash(world)
    _amend(world)
    (world["home"] / "data/d1/new.npz").write_bytes(b"changed again")
    with pytest.raises(SystemExit, match="does not match the amended record"):
        _verify(world)


def test_verify_catches_a_run_started_between_hash_and_amend(world):
    _hash(world)
    world["out"].mkdir(parents=True)
    (world["out"] / "confirm_h4_stage1.started").write_text("")     # stage 1 started after the box hash
    _amend(world)                                                   # the host cannot see the box
    with pytest.raises(SystemExit, match="already run or started"):
        _verify(world)


def test_verify_catches_guarded_code_changed_after_amend(world):
    _hash(world)
    _amend(world)
    (world["repo"] / "csdiar/code.py").write_text("x = 3\n")
    with pytest.raises(SystemExit, match="changed since the freeze"):
        _verify(world)


def test_a_record_without_paths_out_is_refused(world):
    _edit(world["freeze"], lambda r: r.pop("paths"))
    with pytest.raises(SystemExit, match="paths.out"):
        _hash(world)


def test_writes_leave_no_temporary_file(world):
    _hash(world)
    _amend(world)
    assert not list(world["freeze"].parent.glob("*.tmp")) and not list(world["report"].parent.glob("*.tmp"))
